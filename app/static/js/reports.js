const list = document.getElementById("report-list");
const count = document.getElementById("report-count");
const previewTitle = document.getElementById("preview-title");
const summary = document.getElementById("report-summary");
const openLink = document.getElementById("open-report");

function duration(seconds) {
  const total = Math.round(Number(seconds || 0));
  return `${Math.floor(total / 60)}m ${String(total % 60).padStart(2, "0")}s`;
}

function riskClass(value) {
  if (value >= .82) return "danger";
  if (value >= .65) return "warning";
  return "success";
}

function select(report, button) {
  document.querySelectorAll(".report-item").forEach(item => item.classList.remove("active"));
  button.classList.add("active");

  previewTitle.textContent = report.name;
  summary.className = "report-summary";

  const maxRisk = Number(report.maximum_risk || 0);

  summary.innerHTML = `
    <div class="report-visual">
      <div class="report-risk-ring ${riskClass(maxRisk)}" style="--report-risk:${maxRisk * 360}deg">
        <div><strong>${(maxRisk * 100).toFixed(1)}%</strong><span>peak risk</span></div>
      </div>
      <div class="report-grade">
        <span>SESSION INSIGHT</span>
        <strong>${report.alert_count > 1 ? "High attention" : report.alert_count === 1 ? "Review event" : "Stable session"}</strong>
        <p>Dominant signal: ${report.dominant_signal}</p>
      </div>
    </div>

    <div class="report-kpis">
      <article><span>◷ Duration</span><strong>${duration(report.duration_seconds)}</strong></article>
      <article><span>⚠ Controlled alerts</span><strong>${report.alert_count}</strong></article>
      <article><span>↗ Maximum risk</span><strong>${(maxRisk * 100).toFixed(1)}%</strong></article>
      <article><span>◎ Dominant signal</span><strong>${report.dominant_signal}</strong></article>
    </div>

    <div class="report-timeline">
      <span></span><i></i><i class="warning"></i><i></i><i class="danger"></i><i></i><span></span>
    </div>

    <p>This report was generated by the V3 analytics pipeline and remains available to Commander for explanation.</p>
  `;

  if (report.html_file) {
    openLink.href = `/api/reports/${report.id}/view`;
    openLink.classList.remove("hidden");
  } else {
    openLink.classList.add("hidden");
  }
}

fetch("/api/reports")
  .then(response => response.json())
  .then(({reports}) => {
    count.textContent = `${reports.length} reports`;
    document.getElementById("overview-session-count").textContent = reports.length;
    document.getElementById("overview-alert-count").textContent =
      reports.reduce((sum, report) => sum + Number(report.alert_count || 0), 0);
    document.getElementById("overview-max-risk").textContent =
      `${(Math.max(0, ...reports.map(report => Number(report.maximum_risk || 0))) * 100).toFixed(0)}%`;

    if (!reports.length) {
      list.innerHTML = `<div class="empty-state">No JSON reports found in reports/v3.</div>`;
      return;
    }

    list.innerHTML = "";

    reports.forEach((report, index) => {
      const button = document.createElement("button");
      button.className = "report-item";
      const maxRisk = Number(report.maximum_risk || 0);

      button.innerHTML = `
        <span class="report-item-icon">▤</span>
        <div>
          <b>${report.name}</b>
          <span>${duration(report.duration_seconds)} · ${report.alert_count} alerts</span>
        </div>
        <strong class="${riskClass(maxRisk)}">${(maxRisk * 100).toFixed(0)}%</strong>
      `;

      button.addEventListener("click", () => select(report, button));
      list.appendChild(button);

      if (index === 0) select(report, button);
    });
  })
  .catch(error => {
    list.innerHTML = `<div class="empty-state">Reports could not be loaded.</div>`;
    console.error(error);
  });
